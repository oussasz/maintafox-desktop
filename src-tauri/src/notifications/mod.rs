//! Notifications (CMMS alerts and inbox).
//!
//! - `catalog` — fixed vocabulary: modules and their view permission, severities, audiences,
//!   escalation targets (SYSTEM).
//! - `emitter` / `router` — raising an event and choosing its recipients from the category's
//!   rule (COMPANY: Données de référence → Notifications).
//! - `watchers` / `conditions` — notifications derived from record states, and their resolution
//!   when the state clears.
//! - `scheduler` — the per-device sweep (snooze, watchers, resolution, escalation, expiry).
//! - `inbox` / `delivery` — what a person sees and does; `digest`, `os_toast`, `email` — channels.
//! - `config` — the plant's rules and escalation steps.
//!
//! **Sync.** Categories, rules, escalation policies and steps are tenant rows (synchronised to
//! every device). Events are tenant rows; notifications, acknowledgements and preferences belong
//! to their user and reach only that person's devices. Notifications derived from synchronised data
//! (watchers, PM due, SLA breach, certificate expiry, digest, escalation) are generated by every
//! device itself with seeded identities and not sent; read / acknowledge / snooze / archive are
//! sent. `resolved_at` (events and notifications) and `dedupe_key` are device-local; delivery
//! attempts (`notification_deliveries`) and the watcher start marks (`notification_watch_state`)
//! are local tables.

